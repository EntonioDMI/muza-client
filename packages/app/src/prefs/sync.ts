/** СИНХРОНИЗАЦИЯ НАСТРОЕК МЕЖДУ УСТРОЙСТВАМИ.
 *
 *  Зачем. До 2026-08-11 профиля было два и они не знали друг о друге: у
 *  приложения свой на диске, у браузера свой в localStorage. Человек настраивал
 *  вид на компьютере, открывал app.muza.lol и видел дефолты — «в веб-версии
 *  интерфейс старый» (жалоба владельца 11.08) наполовину было именно это.
 *
 *  Модель — ОДИН профиль на аккаунт, последняя запись побеждает. Не CRDT и не
 *  слияние по полям: настройки правит один человек, конфликт «двое одновременно
 *  крутят один ползунок с разных устройств» в реальности не встречается, а
 *  цена слияния по полям — отметка времени у КАЖДОГО из полутора сотен полей.
 *
 *  ⚠️ ЧТО НЕ ЕЗДИТ МЕЖДУ УСТРОЙСТВАМИ — список `SYNC_LOCAL` ниже. Он закрыт
 *  тестом (sync.coverage.test.ts): новый ключ Prefs обязан попасть либо в него,
 *  либо в синхронизируемые, иначе сборка красная. Это тот же приём, которым
 *  закрыт разъезд THEME_KEYS/THEME_EXCLUDED, и заведён он по той же причине:
 *  забытый ключ — это не «мелочь», а настройка, молча уехавшая на чужую машину.
 *
 *  ⚠️ СЕРВЕР МОЖЕТ БЫТЬ СТАРЕЕ КЛИЕНТА. Веб и приложение выкладываются отдельно
 *  от сервера, и на проде клиент регулярно новее. Ручки `/me/prefs` там нет —
 *  `getPrefs()` отвечает `supported: false`, и синхронизации просто не
 *  существует: локальные настройки не трогаются, наверх ничего не уходит,
 *  человеку ничего не показывается. Отсутствие функции — не поломка. */

import type { MuzaApi } from "@muza/api-client";
import { DEFAULT_PREFS, type Prefs } from "./types";

/** Ключи, которые ОСТАЮТСЯ НА ЭТОМ УСТРОЙСТВЕ.
 *
 *  Правило отбора одно: ключ описывает не вкус человека, а железо или экран
 *  перед ним. Такой ключ, приехав с другой машины, в лучшем случае бессмыслен,
 *  в худшем — ломает звук (id устройства, которого здесь нет).
 *
 *  Всё остальное ездит: тема, раскладка, акцент, шрифты, плотность, тексты
 *  песен, воспроизведение, горячие клавиши, состав вкладок и кнопок. */
export const SYNC_LOCAL = [
  // ── Железо: этих устройств на другой машине нет ──────────────────────
  // (`deviceId` сюда не входит — это поле ВНУТРИ маршрута вывода, а не
  //  настройка верхнего уровня; список маршрутов целиком закрыт `audioOutputs`.)
  "audioOutputs",
  "outputProfiles",
  "activeOutputProfile",
  "micDeviceId",
  "micDeviceLabel",
  // ── Экран: телефон, ноутбук и монитор 4K требуют разного ─────────────
  // Масштаб, снятый с 27-дюймового монитора, на телефоне нечитаем — и
  // наоборот. Это единственная настройка ВИДА в этом списке, и она здесь
  // именно потому, что «правильное» значение задаёт экран, а не человек.
  "uiScale",
  // ── Про эту установку, а не про аккаунт ──────────────────────────────
  "autostart",
  "closeToTray",
  "tray",
  "miniPlayer",
  "cacheLimitGb",
  // Метка схемы профиля: ею заведует миграция (prefs/load.ts), а не человек.
  // Приехав с устройства со старой версией клиента, она отмотала бы номер
  // назад и запустила миграцию повторно.
  "lookVersion",
] as const;

const LOCAL = new Set<string>(SYNC_LOCAL);

/** Что уходит на сервер: профиль без ключей устройства. */
export function toServerPrefs(prefs: Prefs): Record<string, unknown> {
  const out: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(prefs)) if (!LOCAL.has(k)) out[k] = v;
  return out;
}

/** Что применяется из серверного профиля: серверные значения поверх текущих,
 *  но ключи устройства берутся ТОЛЬКО из текущих.
 *
 *  ⚠️ Неизвестные ключи сервера отбрасываются. Профиль мог быть записан более
 *  новым клиентом, и подсунуть его поля в состояние — значит протащить в
 *  настройки то, чего этот клиент не понимает. */
export function fromServerPrefs(server: Record<string, unknown>, current: Prefs): Prefs {
  const next: Record<string, unknown> = { ...current };
  for (const [k, v] of Object.entries(server)) {
    if (LOCAL.has(k)) continue;
    if (!(k in DEFAULT_PREFS)) continue;
    next[k] = v;
  }
  // Через unknown: с точки зрения типов это словарь, но собран он из полей
  // Prefs (чужие ключи отброшены выше), и форма гарантирована этой проверкой,
  // а не системой типов.
  return next as unknown as Prefs;
}

/** Изменились ли синхронизируемые ключи. Сравнение по JSON — профиль плоский
 *  по смыслу (числа, строки, короткие списки), и глубокое сравнение здесь
 *  стоило бы дороже, чем строка на пару килобайт.
 *
 *  Нужно, чтобы не слать на сервер правку ключа устройства: выбранный выход
 *  звука или id микрофона меняются часто и синхронизации не подлежат. */
export function sameServerPrefs(a: Prefs, b: Prefs): boolean {
  return JSON.stringify(toServerPrefs(a)) === JSON.stringify(toServerPrefs(b));
}

export interface PrefsSyncDeps {
  api: MuzaApi;
  /** Сейчас есть серверная сессия. У анонима синхронизировать нечего и некуда. */
  signedIn: boolean;
  getPrefs: () => Prefs;
  applyPrefs: (p: Prefs) => void;
  /** Куда класть отметку «этот профиль уже согласован с сервером». Хранится
   *  ВНЕ Prefs намеренно: попав в профиль, она сама стала бы изменением,
   *  которое надо отправить, и цикл бы не сошёлся. */
  readStamp: () => string | null;
  writeStamp: (v: string | null) => void;
}

/** Первое согласование при входе.
 *
 *  Развилка ровно одна и решается отметкой времени:
 *   - сервер не умеет — ничего не делаем;
 *   - профиля на сервере нет — заливаем свой (первое устройство аккаунта);
 *   - профиль есть и его отметка НЕ СОВПАДАЕТ с нашей — принимаем серверный.
 *     Совпадение отметок означает «это ровно то, что мы сами и залили».
 *
 *  Возвращает `true`, если синхронизация в этом сеансе жива (сервер умеет). */
export async function pullPrefs(deps: PrefsSyncDeps): Promise<boolean> {
  if (!deps.signedIn) return false;
  const res = await deps.api.getPrefs();
  if (!res.supported) return false;

  if (!res.prefs) {
    const saved = await deps.api.putPrefs(toServerPrefs(deps.getPrefs()));
    if (saved) deps.writeStamp(saved.updatedAt);
    return saved !== false;
  }

  if (res.prefs.updatedAt !== deps.readStamp()) {
    deps.applyPrefs(fromServerPrefs(res.prefs.data, deps.getPrefs()));
    deps.writeStamp(res.prefs.updatedAt);
  }
  return true;
}

/** Отправить текущий профиль. Зовётся с задержкой после правки — см.
 *  `usePrefsSync`. Возвращает `false`, если сервер не умеет. */
export async function pushPrefs(deps: PrefsSyncDeps): Promise<boolean> {
  if (!deps.signedIn) return false;
  const saved = await deps.api.putPrefs(toServerPrefs(deps.getPrefs()));
  if (saved === false) return false;
  deps.writeStamp(saved.updatedAt);
  return true;
}
