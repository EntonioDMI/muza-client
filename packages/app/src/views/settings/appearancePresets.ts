/** Три готовых облика («Муза», «Пламя», «Графит») и текущий цвет акцента.
 *
 *  Живёт отдельным файлом, потому что этим пользуются ДВА экрана: плитки
 *  облика рисует раздел «Внешний вид», а тем же цветом акцента под-экран
 *  «Кастомизация» засевает роли акцента при их включении. Две копии этих
 *  шести чисел разъехались бы на первой же смене фирменного синего. */

import type { Prefs } from "../../prefs/types";
import type { TranslationKey, TParams } from "../../i18n";

/** Функция перевода — та же, что отдаёт useT().t. */
type T = (key: TranslationKey, params?: TParams) => string;

/** ТРИ ПРИВЫЧНЫХ СКРУГЛЕНИЯ — теперь просто ЗАСЕЧКИ на непрерывной шкале.
 *
 *  До 2026-08-13 это были единственные три значения, какие человек мог выбрать
 *  («три зашитых варианта, которые он не может изменить», жалоба владельца).
 *  Теперь ползунок «Скругление» даёт любое число 0–40, а эти три остаются
 *  быстрыми чипами над ним: частое — в один клик, редкое — рукой. Числа = --r-lg
 *  бывших пресетов mild/soft/round (tokens/radius.css), поэтому у выбравшего
 *  «Больше» не меняется ни пиксель.
 *
 *  Отсюда же их берёт ряд настроек (AppearancePane) — второй копии этих трёх
 *  чисел в интерфейсе быть не должно. */
export const RADIUS_MILD = 8;
export const RADIUS_SOFT = 16;
export const RADIUS_ROUND = 28;

/** Порядок чипов ряда «Скругление» — он же порядок нарастания. */
export const RADIUS_CHIPS = [
  { key: "mild", value: RADIUS_MILD },
  { key: "soft", value: RADIUS_SOFT },
  { key: "round", value: RADIUS_ROUND },
] as const;

export interface AppearancePreset {
  key: string;
  name: string;
  hint: string;
  accent: Prefs["accent"];
  accentColor: string;
  /** Опорное скругление в px — то же число, что у ползунка «Скругление»
   *  (Prefs.radius). Было тремя именами до 2026-08-13; облик по-прежнему задаёт
   *  ОДНО из трёх привычных значений, просто теперь их можно догнать рукой. */
  radius: number;
  /** Остальные ключи облика, если пресет меняет не только цвет и углы.
   *  Нужен ровно «Классике»: она возвращает ГЕОМЕТРИЮ до редизайна 04.08,
   *  а не только форму углов. Пресеты без него ведут себя как раньше. */
  extra?: Partial<Prefs>;
}

/** РАСКЛАДКИ ОКНА — отдельная ось от обликов (решение владельца 04.08 ночью:
 *  «не стоило добавлять воздух и классику в тему, это совсем не подходит»).
 *  Облик — это цвет и углы; раскладка — геометрия окна. Смешивать их в одном
 *  ряду плиток было ошибкой ещё и механикой: пресет менял ЧАСТЬ геометрии, и
 *  щелчок «Классика» + тумблер плоского давали кентавра — плавающий плеер при
 *  прижатых зонах, у которого «полоска прогресса вылазит за плеер».
 *  Каждая раскладка задаёт ось ЦЕЛИКОМ — смешанных состояний не существует.
 *
 *  air — дефолт (выбор сооснователя), flat — набросок владельца («кому надо —
 *  тот включит»), classic — вид до редизайна 04.08 (обещание: смена дефолта
 *  никого не грабит).
 *
 *  ⚠️ «Число в число» у классики с 05.08 относится к МЕТРИКАМ (плавающий плеер,
 *  сайдбар 280, полоса 92, обложка 60, круглые углы), но НЕ к скруглению зон:
 *  прежняя пара «поле 20 / скругление 28» была не характером, а той самой
 *  поломкой, из-за которой владелец и сказал «интерфейс разрозненный». Она
 *  сведена — обоснование у ключа radiusPanels ниже. */
export type WindowLayout = "air" | "flat" | "classic";

/** ⚠️ КАЖДАЯ РАСКЛАДКА ЗАДАЁТ ОДИН И ТОТ ЖЕ НАБОР КЛЮЧЕЙ (ревизия 05.08).
 *  Раньше `density` и `radiusPanels` стояли только у «Классики», и переход
 *  «Классика → Воздушная» оставлял её плотность в воздушной геометрии: поле
 *  зоны 20px против скругления 16px. Ось, заданная наполовину, — это тот же
 *  кентавр, ради которого раскладки и вынесли из обликов; недостающий ключ
 *  здесь стоит дороже, чем лишний. */
export const WINDOW_LAYOUTS: Record<WindowLayout, Partial<Prefs>> = {
  air: {
    zonesDocked: false,
    playerDocked: true,
    gapZone: 8,
    wSidebar: 240,
    hPlayerBar: 72,
    coverBarSize: 48,
    radius: RADIUS_SOFT,
    // 50 → поле зоны 16px = --r-lg пресета "soft" (16px). Концентрично.
    density: 50,
    radiusPanels: 100,
  },
  flat: {
    zonesDocked: true,
    playerDocked: true,
    gapZone: 0,
    wSidebar: 240,
    hPlayerBar: 72,
    coverBarSize: 48,
    radius: RADIUS_SOFT,
    density: 50,
    radiusPanels: 100,
  },
  classic: {
    zonesDocked: false,
    playerDocked: false,
    gapZone: 12,
    wSidebar: 280,
    hPlayerBar: 92,
    coverBarSize: 60,
    // 83, а не «прежние» 50: формула плотности сменилась редизайном
    // (densityPad 14+12d/100 → 10+12d/100), и старые 50 теперь дают поле зоны
    // 16px вместо исторических 20. Обещание «число в число» — про РЕЗУЛЬТАТ:
    // 10 + round(12·83/100) = 20 (ревизия 04.08).
    density: 83,
    radius: RADIUS_ROUND,
    // ЧИНИМ КОНЦЕНТРИЧНОСТЬ КЛАССИКИ (правка владельца 05.08).
    //
    // Что было сломано: при radius "round" --r-lg = 28px, а поле зоны при
    // density 83 = 20px. 28 против 20 — ровно та геометрия, которую редизайн
    // 04.08 назвал причиной жалобы «интерфейс разрозненный»: угол зоны
    // отворачивается от соседей сильнее, чем зоны разделены, и на каждом стыке
    // появляется диагональная пустота (см. шапку tokens/radius.css).
    //
    // Почему НЕ density. Инвариант надо свести к одному числу, и подтянуть
    // можно либо поле вверх, либо скругление вниз. Поле вверх не идёт: формула
    // 10 + round(12·d/100) даёт максимум 22 даже при d=100 — до 28 через
    // плотность не добраться в принципе. Вдобавок density тянет за собой высоту
    // строки трека, и ради углов пришлось бы менять списки.
    //
    // Почему radiusPanels. Это ПРОЦЕНТ ОТ ПРЕСЕТА, то есть единственная ручка,
    // которая двигает скругление ЗОН (--r-lg/--r-xl), не трогая ни пресет
    // "round", ни скругление плиток и строк (те живут на radiusTiles и остаются
    // круглыми). Классика сохраняет узнаваемый круглый характер везде, кроме
    // одного места, где он и мешал, — на стыках зон.
    // 71% → round(28 · 0.71) = 20 = поле зоны. Инвариант сведён.
    radiusPanels: 71,
  },
};

/** КЛЮЧИ СИЛУЭТА — по ним и только по ним узнаётся раскладка.
 *
 *  Остальные числа набора (ширина сайдбара, высота полосы, плотность) человек
 *  штатно крутит ползунками и в режиме правки вида — сузивший сайдбар на 20px
 *  всё ещё сидит в «Воздушной», и объявлять его раскладку «никакой» было бы
 *  враньём. А вот силуэт руками не собирают: у зазора зон свой ползунок, но
 *  пара «зоны с зазором + прижатый плеер» — это и есть выбор раскладки. */
const LAYOUT_SIGNATURE = ["zonesDocked", "playerDocked", "gapZone"] as const;

/** Какая раскладка стоит сейчас; null — ни одна не совпала («Своя»).
 *
 *  Возвращать «Воздушную» по остатку было ОШИБКОЙ (найдена 05.08 в живом
 *  профиле владельца): профиль, проехавший отменённую ступень v3, имел
 *  zonesDocked false + gapZone 0 — вкладки утверждали «Воздушная», а зоны
 *  стояли впритык и со скруглением. Человек не нажимает уже выбранное, значит
 *  и не чинится, хотя починка была в один клик (Tabs зовёт onChange и по
 *  выбранному сегменту). Честное «ни одна» — это то, что делает расхождение
 *  видимым. */
export function currentWindowLayout(prefs: Prefs): WindowLayout | null {
  const keys = Object.keys(WINDOW_LAYOUTS) as WindowLayout[];
  return keys.find((k) => LAYOUT_SIGNATURE.every((s) => WINDOW_LAYOUTS[k][s] === prefs[s])) ?? null;
}

