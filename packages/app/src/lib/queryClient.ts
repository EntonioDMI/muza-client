/** ОДИН клиент запросов на обе программы (приложение и веб).
 *
 *  ЗАЧЕМ ОН ВООБЩЕ ПОЯВИЛСЯ (жалоба владельца 6 из семи, 12.08: «Главная
 *  грузится от полусекунды до целой, Любимое около секунды, плейлисты тоже»).
 *  Кэша на клиенте не было НИКАКОГО — ни react-query, ни своего: каждый вызов
 *  api это свежий fetch. А экраны пересобираются целиком при каждой навигации
 *  (`<main key={rendered}>` в App.tsx), то есть эффект монтирования срабатывает
 *  заново и шлёт запрос заново. Ничего не переиспользовалось вообще — отсюда и
 *  ощущение, что «страницы стали грузиться медленнее»: они всегда грузились с
 *  нуля, просто данных стало больше.
 *
 *  ЧТО СЧИТАТЬ СВЕЖИМ. Ключевая настройка здесь — staleTime, и она НЕ про
 *  экономию трафика, а про то, что человек считает правдой:
 *   - лента Главной пересобирается сервером не чаще, чем накапливается история
 *     прослушиваний; минута — это заведомо чаще, чем она реально меняется;
 *   - «Любимое» и плейлисты человек правит САМ и ждёт мгновенного отклика,
 *     поэтому их свежесть держится не таймером, а инвалидацией ключа в момент
 *     правки (см. QK ниже).
 *
 *  ЧЕГО ЗДЕСЬ НАРОЧНО НЕТ:
 *   - refetchOnWindowFocus — приложение живёт в окне, которое сворачивают и
 *     разворачивают десятки раз за сессию; перезапрос на каждый возврат к окну
 *     это ровно та лавина, от которой мы уходим;
 *   - повторы при отказе. У экранов есть свой фолбэк (снимок последнего ответа
 *     в приложении, пустой список в вебе), а три молчаливых повтора превращают
 *     лежащий сервер в тридцатисекундный спиннер вместо честного «пусто». */

import { useRef } from "react";
import { QueryClient, useQueryClient } from "@tanstack/react-query";

/** Ключи запросов в одном месте: разъехавшийся ключ — это тихий промах кэша,
 *  который выглядит как «кэш не работает», а не как опечатка.
 *
 *  ⚠️ userId в ключи НЕ входит — и это осознанно: кэш скоупится не ключом, а
 *  сбросом при смене пользователя (useQueryScope ниже). Ключ с userId пришлось
 *  бы протаскивать в каждый вызов useQuery/invalidateQueries, и любое забытое
 *  место снова показывало бы чужие данные — то есть ровно тот дефект, от
 *  которого уходим. Сброс — одно место и не забывается. */
export const QK = {
  home: ["home"] as const,
  favorites: ["favorites"] as const,
  playlist: (id: string) => ["playlist", id] as const,
  playlists: ["playlists"] as const,
} as const;

export function createQueryClient(): QueryClient {
  return new QueryClient({
    defaultOptions: {
      queries: {
        staleTime: 60_000,
        // Данные держим дольше, чем считаем свежими: возврат на экран рисует
        // прошлый ответ мгновенно и обновляет его в фоне — вместо спиннера.
        gcTime: 10 * 60_000,
        refetchOnWindowFocus: false,
        retry: false,
      },
    },
  });
}

/** Привязать кэш запросов к текущему пользователю: сменился — выбросить всё.
 *
 *  ЗАЧЕМ (жалоба владельца 16.08 «рекомендации будто смешиваются с чужими»).
 *  На сервере они не смешиваются — все сигналы читаются WHERE user_id =
 *  текущий. Смешивался кэш ЗДЕСЬ: клиент запросов один на окно и живёт дольше
 *  сессии, ключи (`["home"]`, `["favorites"]`, `["playlists"]`) пользователя не
 *  различают, gcTime — 10 минут, а при логауте кэш никто не трогал. Вышел A,
 *  вошёл B в том же окне — и B первым кадром видел ленту A, пока в фоне не
 *  доедет его собственная.
 *
 *  ⚠️ ЗОВЁТСЯ В ТЕЛЕ РЕНДЕРА, НЕ В ЭФФЕКТЕ — и это принципиально. Эффекты детей
 *  выполняются РАНЬШЕ эффектов родителя, поэтому сброс из useEffect опоздал бы:
 *  экран уже отрисовал бы чужие данные, и человек увидел бы их кадром. В теле
 *  родителя сброс происходит до того, как дети вообще начнут рендериться.
 *  Тот же приём и по той же причине — у setSnapshotScope в App.tsx.
 *
 *  Первый вызов ничего не сбрасывает: сбрасывать там нечего, а лишний clear
 *  снёс бы запросы, уже улетевшие при восстановлении сессии. */
export function useQueryScope(userId: string | null): void {
  const qc = useQueryClient();
  const scopedFor = useRef<string | null | undefined>(undefined);
  if (scopedFor.current !== userId) {
    const first = scopedFor.current === undefined;
    scopedFor.current = userId;
    if (!first) qc.clear();
  }
}
