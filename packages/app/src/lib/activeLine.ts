/** Какая строка текста поётся прямо сейчас — ОДНА реализация на обе программы.
 *
 *  Жила в теле App.tsx как useMemo по [pos, ...], потом переехала в
 *  apps/desktop/src/player/activeLine.ts (позиция перестала быть состоянием
 *  React — см. positionStore.ts, считать надо ПРЯМО НА ТИКЕ), а сюда — когда
 *  выяснилось, что у веба всё это время лежала СВОЯ копия правила «нотки»
 *  (apps/web/src/components/LyricsPanel.tsx) с теми же числами 2..8 и своим
 *  циклом. Копия, обязанная совпадать, разъезжается на первой же правке —
 *  а править пришлось именно её (упреждение ниже).
 *
 *  Функция чистая и дешёвая: её зовут ~4 раза в секунду на каждый смонтированный
 *  текст (панель «Сейчас играет» и оверлей караоке), а перерисовка происходит
 *  только когда НОМЕР строки сменился — раз в несколько секунд.
 *
 *  ⚠️ Строка НЕ ищется бинарно намеренно: список — десятки строк, а линейный
 *  проход не зависит от того, отсортирован ли источник (у LRC бывают дубли
 *  таймкодов, см. parseLrc на сервере). */

/** Всё, что нужно от строки, чтобы понять, поётся ли она. Структурный тип, а не
 *  импорт LyricLine: у приложения и веба свои формы строки (у одной есть note,
 *  у другой text вместо line), общее у них — ровно момент времени. */
export interface TimedLine {
  t: number;
}

/** УПРЕЖДЕНИЕ ПОДСВЕТКИ, мс — почему текст «отстаёт», даже когда таймкоды точны.
 *
 *  Правило `l.t <= pos` зажигает строку не в её момент, а на ПЕРВОМ ТИКЕ ПОСЛЕ
 *  него, и тик приходит редко: нативный движок опрашивается раз в 250 мс
 *  (player/nativeEngine.ts, POLL_MS), веб-путь живёт на событии timeupdate
 *  (~4 раза в секунду, в WebView2 грубее). То есть значение позиции в момент
 *  сравнения уже устарело в среднем на полпериода — 125 мс, в худшем на 250.
 *  Сверху ложится показ: цвет и масштаб строки едут --dur-lyric = 400 мс
 *  (packages/ui/src/tokens/effects.css), и «загорелась» человек читает не в
 *  начале перехода, а где-то к его середине.
 *
 *  250 мс — это один период опроса: он покрывает среднюю староту значения и
 *  примерно половину цветового перехода. Больше брать нельзя — упреждение
 *  свыше периода начнёт зажигать строку до того, как её запели, и это заметно
 *  сильнее, чем опоздание: глаз прощает «чуть позже», но не «текст спойлерит».
 *
 *  ⚠️ Это компенсация ПОКАЗА, а не сдвиг песни: на перемотку по строке она не
 *  влияет (lyricSeekSec ниже её не вычитает). */
export const LYRICS_LEAD_MS = 250;

export interface ActiveLineOpts {
  /** Текст с таймкодами И включённая настройка «синхронный текст».
   *  false — активной строки нет вовсе (plain-список). */
  synced: boolean;
  /** prefs.lyricsEndNote: после последней строки активная переезжает на
   *  виртуальный индекс lyrics.length — «текст кончился, доигрывает музыка». */
  endNote: boolean;
  /** prefs.lyricsOffsetMs: ручная поправка человека поверх упреждения.
   *  Плюс — показывать раньше, минус — позже. Нужна там, где врут САМИ
   *  таймкоды: в LRCLIB полно текстов, размеченных ровной сеткой «строка
   *  каждые 2 секунды» (проверено 16.08 на «ЯРЧЕ СОЛНЦА — Наблюдатель»,
   *  записи 33400694 и 34755407 — обе такие), и одна запись LRC часто
   *  разложена на издания разной длины. Такое не лечится ни одной константой
   *  на нашей стороне — только рукой. */
  offsetMs?: number;
}

export function activeLyricLine(pos: number, lyrics: readonly TimedLine[], opts: ActiveLineOpts): number {
  if (!opts.synced) return -1;
  // Одна поправка на оба сравнения (строка и «нотка»): если сдвинуть только
  // выбор строки, нотка загорится не там, где кончился текст.
  const p = pos + (LYRICS_LEAD_MS + (opts.offsetMs ?? 0)) / 1000;
  let a = 0;
  lyrics.forEach((l, i) => {
    if (l.t <= p) a = i;
  });
  // Последнюю строку держим примерно столько, сколько типичную (зазор до
  // предпоследней), в рамках 2..8с — иначе нотка загоралась бы синей ещё
  // пока последняя строка поётся.
  if (opts.endNote && lyrics.length > 0 && a === lyrics.length - 1) {
    const last = lyrics[a].t;
    const prev = lyrics.length > 1 ? lyrics[a - 1].t : last - 4;
    const hold = Math.min(8, Math.max(2, last - prev));
    if (p - last >= hold) a = lyrics.length;
  }
  return a;
}

/** Куда перематывать по клику на строку.
 *
 *  Упреждение здесь НЕ вычитается: оно про то, когда ПОКАЗАТЬ строку, а не про
 *  то, где она звучит. А вот ручная поправка — вычитается: человек ставит её
 *  именно потому, что таймкод не совпадает со звуком, и клик по строке обязан
 *  попадать туда же, куда попадает подсветка. */
export function lyricSeekSec(t: number, offsetMs = 0): number {
  return Math.max(0, t - offsetMs / 1000);
}
