/** Правила статуса «слушает Muza» в Discord — ЧИСТАЯ часть: как собирается
 *  строка активности, какая ссылка считается годной для кнопки и какой адрес
 *  обложки Discord покажет без полей.
 *
 *  Переехало из apps/desktop/src/lib/discord.ts (волна «настройки»,
 *  2026-08-02): по этим же правилам под-экран настроек рисует ПРЕДПРОСМОТР
 *  активности, а он теперь общий. Мост к самому Discord (invoke в rpc.rs) на
 *  старом месте и остался — он площадочный; там же стоит ре-экспорт этих трёх
 *  функций, чтобы у приложения и его тестов не поехали импорты.
 *
 *  ⚠️ Правила ДОЛЖНЫ совпадать с тем, что делает мост: предпросмотр, который
 *  показывает кнопку, а она не уходит, — хуже отсутствия предпросмотра. */

/** Кнопку реально шлём только с годным http(s)-адресом — мост молча
 *  отбрасывает прочее, и предпросмотр обязан показывать ту же правду. */
export function isValidButtonUrl(url: string): boolean {
  return /^https?:\/\/\S+$/.test(url.trim());
}

/** Шаблон строки активности: подстановки {track}/{artist}/{album}. Пустые
 *  значения подчищаются вместе с висячими разделителями (« — », «·»…):
 *  "{artist} — {album}" без альбома отдаёт просто артиста. Предел Discord —
 *  128 символов. */
export function formatTemplate(tpl: string, vars: { track: string; artist: string; album?: string }): string {
  const out = tpl
    .replaceAll("{track}", vars.track)
    .replaceAll("{artist}", vars.artist)
    .replaceAll("{album}", vars.album ?? "")
    // разделители, повисшие на месте пустой подстановки
    .replace(/^[\s\-—–·|:]+/, "")
    .replace(/[\s\-—–·|:]+$/, "")
    .replace(/\s{2,}/g, " ");
  return out.slice(0, 128);
}

/** Обложка для Discord-активности. Discord тянет внешний https-адрес как есть
 *  и НЕ кропает его (в статусе получался кадр с полями), а локальные байты
 *  ему не отдать. Для тумб YouTube берём центральный квадрат через публичный
 *  резайз-прокси: у музыкальных тумб арт всегда ровно по центру кадра
 *  (480×360 → арт 360×360, 1280×720 → 720×720), так что слепой центральный
 *  кроп режет точно по арту. Прокси упал — Discord просто покажет активность
 *  без картинки, это не ошибка. Остальные источники и так квадратные. */
export function discordCoverUrl(raw: string | null): string | null {
  if (!raw || !raw.startsWith("https")) return null;
  try {
    if (!/(^|\.)ytimg\.com$/.test(new URL(raw).hostname)) return raw;
  } catch {
    return null; // кривой адрес из каталога — лучше без картинки, чем падение
  }
  // trim=30 — автообрезка однотонных полей ДО квадратного кропа: у тумб
  // рамки ДВОЙНЫЕ (широкий кадр в холсте 4:3 + поля вокруг самого арта), и
  // слепой центральный квадрат оставлял боковые полосы внутри.
  // Проверено на тёмных и светлых артах: поля уходят, арт не отъедается.
  return `https://images.weserv.nl/?url=${encodeURIComponent(raw)}&trim=30&w=600&h=600&fit=cover`;
}
