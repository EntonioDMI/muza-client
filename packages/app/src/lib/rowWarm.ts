/** ОДНА форма пропсов «подготовки строки трека» для всех общих экранов.
 *
 *  ЧТО ЭТО. Приложение, пока курсор идёт по списку, заранее разбирает, откуда
 *  возьмётся звук ближайших строк, — чтобы клик стартовал мгновенно. Умение
 *  приезжает в общий экран ПРОПОМ (`warmRow`/`rowProps`), а не хуком: сама
 *  подготовка — приложенческая (движок в Rust), в общий пакет она не едет.
 *  У браузера умения нет — пропа нет, и на обёртку строки ничего не вешается.
 *
 *  ПОЧЕМУ ОТДЕЛЬНЫМ ФАЙЛОМ (чистка дублей волны 3, 2026-08-02). Одна и та же
 *  форма была объявлена ПЯТЬ раз независимо — HomeFeed (HomeRowWarmProps),
 *  FavoritesView (RowWarmProps), SearchView, PlaylistView (инлайн) и StatsView
 *  (безымянный React.ComponentProps<"div">). Пять копий расходились уже на
 *  старте: где-то поля были обязательными, где-то нет, элемент был то
 *  HTMLElement, то HTMLDivElement. Правка одного экрана молча оставляла
 *  остальные со старой формой, а StatsView вообще принимал любые пропсы div.
 *
 *  ПОЧЕМУ НЕ ИМПОРТ ИЗ ПРИЛОЖЕНИЯ. Первоисточник формы —
 *  apps/desktop/src/player/useWarmer.ts::WarmRowProps, но импортировать её
 *  оттуда нельзя: тот модуль тянет Tauri-движок. TypeScript структурный, так
 *  что десктопный `useWarmRow()` подставляется сюда без приведения.
 *
 *  ПОЧЕМУ ПОЛЯ НЕОБЯЗАТЕЛЬНЫ. Умение может быть у площадки частичным (греть
 *  только по наведению, без наблюдения за видимостью) — правило розетки «нет
 *  умения → нет поведения» действует и внутри одного пропа.
 *
 *  ПОЧЕМУ ref ПРИНИМАЕТ HTMLElement, А НЕ HTMLDivElement. Так шире: обёртка
 *  строки у экранов — div, и он подходит под HTMLElement; обратное неверно. */

/** Пропсы на обёртку строки трека. Раскладываются спредом: {...warmRow(id)}. */
export interface RowWarmProps {
  /** React 19 ref-cleanup: наблюдение снимается ВОЗВРАТОМ функции, ref(null)
   *  ждать не нужно. */
  ref?: (el: HTMLElement | null) => (() => void) | undefined;
  onMouseEnter?: () => void;
  /** Палец/кнопка легли на строку — клик почти неизбежен, готовим срочно. */
  onPointerDown?: () => void;
}

/** Проп общих экранов: по id строки — пропсы её обёртки. */
export type WarmRow = (id: string) => RowWarmProps;
