/** ПЕРЕХОД МЕЖДУ ЭКРАНАМИ: старый уходит, потом приходит новый.
 *
 *  ЧТО БЫЛО НЕ ТАК (жалоба владельца 05.08: «переходы стали хуже, интерфейс
 *  кажется вечно бетой»). Смена экрана меняла `view`, React ремонтировал всё
 *  поддерево — и старое содержимое исчезало КАДРОМ. Единственным движением был
 *  вход нового: `.muza-view` растворялся 120 мс. То есть переход состоял ровно
 *  из половины: уходить было некому, потому что уходящего уже не существовало.
 *
 *  КАК УСТРОЕНО. Хук разводит «что человек выбрал» и «что сейчас нарисовано».
 *  Пока идёт уход, нарисован ПРЕЖНИЙ экран — ему и есть что анимировать. Когда
 *  уход доиграл, нарисованное догоняет выбранное, поддерево ремонтируется, и
 *  новый экран играет свой вход.
 *
 *  ⚠️ ВЫДЕРЖКИ МЕЖДУ УХОДОМ И ПРИХОДОМ НЕТ НАМЕРЕННО, хотя в плане она была.
 *  На тяжёлом экране (Главная с полками) коммит нового `rendered` заставляет
 *  React отрисовать всё поддерево синхронно — браузер не может рисовать эти
 *  50–100 мс, то есть пауза УЖЕ есть, просто вынужденная. Добавить к ней
 *  намеренные 40 мс значило бы удвоить единственное место, где переход и так
 *  ощутимо стоит. Токен --dur-view-hold из шкалы поэтому снят.
 *
 *  ⚠️ ДЛИТЕЛЬНОСТЬ ЧИТАЕТСЯ С УЗЛА, А НЕ ЗАШИТА ЧИСЛОМ. Ползунок «Переходы
 *  страниц» умножает --dur-view-out, и таймер, не знающий об этом, снимал бы
 *  старый экран на середине его собственного затухания. Тот же приём и по той
 *  же причине, что в packages/ui/src/lib/useLayerState.js.
 *
 *  Веб этим хуком НЕ пользуется: у Next App Router нет фазы «до коммита
 *  маршрута», перехватывать там нечего — вебу достаётся только вход. */

import { useEffect, useRef, useState } from "react";
import { readDurationMs } from "@muza/ui";

/** Фаза для разметки: `out` — прежний экран уходит, `in` — текущий пришёл. */
export type ViewPhase = "in" | "out";

/** Страховка на случай, если длительность прочитать не удалось (jsdom, узла
 *  ещё нет). 120 мс — прежнее поведение перехода, то есть заведомо не хуже. */
const FALLBACK_OUT_MS = 120;

export function useViewTransition<V>(view: V): {
  /** Что рисовать. Во время ухода — ПРЕЖНИЙ экран. */
  rendered: V;
  phase: ViewPhase;
  /** Повесить на узел, который анимируется (он же меряется на длительность). */
  ref: (el: HTMLElement | null) => void;
} {
  const [rendered, setRendered] = useState(view);
  const [phase, setPhase] = useState<ViewPhase>("in");
  const nodeRef = useRef<HTMLElement | null>(null);
  const timer = useRef<ReturnType<typeof setTimeout> | null>(null);
  /** Куда едем. В рефе, а не в состоянии: таймер обязан видеть САМЫЙ свежий
   *  выбор, иначе быстрый Главная→Библиотека→Статистика приземлится на
   *  промежуточном экране, который человек уже проскочил. */
  const target = useRef(view);
  target.current = view;

  useEffect(() => {
    if (view === rendered) {
      // ⚠️ ВЕРНУЛИСЬ ТУДА, ОТКУДА УХОДИЛИ. Без этой ветки экран оставался в
      // фазе ухода НАВСЕГДА — то есть с opacity 0. Человек щёлкает «Библиотека»
      // и тут же обратно «Главная», рисуемое так и не менялось, ранний возврат
      // проглатывал случай, а таймер уже был снят. Поймано собственным тестом.
      if (timer.current !== null) {
        clearTimeout(timer.current);
        timer.current = null;
      }
      setPhase("in");
      return;
    }
    setPhase("out");
    // ⚠️ УХОД УЖЕ ИДЁТ — НЕ ПЕРЕЗАПУСКАЕМ. Иначе каждый следующий щелчок по
    // сайдбару добавлял бы полный уход заново, и на быстром переборе экран
    // висел бы погашенным сильно дольше собственной анимации.
    if (timer.current !== null) return;
    const node = nodeRef.current;
    const ms = node ? readDurationMs(node) : 0;
    timer.current = setTimeout(
      () => {
        timer.current = null;
        // Догоняем САМЫЙ свежий выбор, а не тот, что был на старте ухода.
        setRendered(target.current);
        setPhase("in");
      },
      ms > 0 ? ms : FALLBACK_OUT_MS,
    );
  }, [view, rendered]);

  // Снятие таймера — ОТДЕЛЬНЫМ эффектом на размонтирование. В уборке основного
  // он гасил бы собственный полёт при каждой смене зависимостей.
  useEffect(
    () => () => {
      if (timer.current !== null) {
        clearTimeout(timer.current);
        timer.current = null;
      }
    },
    [],
  );

  return {
    rendered,
    phase,
    ref: (el) => {
      nodeRef.current = el;
    },
  };
}
