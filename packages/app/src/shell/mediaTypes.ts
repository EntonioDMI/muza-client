/** Формы данных, которые нужны общим экранам «Сейчас играет» и полноэкранному
 *  режиму (Э7 веб-паритета).
 *
 *  ПОЧЕМУ ЗДЕСЬ, А НЕ ССЫЛКА НА PlayerTrack ДЕСКТОПА. У клиентов свои модели
 *  трека: у приложения это apps/desktop/src/player/types.ts (kind, loudness,
 *  localHash — знание движка добычи), у веба — Track контракта @muza/api-client
 *  (coverUrl/durationSec). Общему экрану ни то ни другое не нужно: он рисует
 *  название, автора, альбом, обложку и длительность. Тип описывает ровно этот
 *  минимум, и обе модели подходят под него СТРУКТУРНО — приложениям не надо ни
 *  конвертировать свои треки, ни импортировать этот файл.
 *
 *  Файл внутренний: подпуть "@muza/app/shell/*" ведёт на *.tsx, снаружи пакета
 *  этот модуль не виден — и не должен быть. Нужны типы вовне — значит, кто-то
 *  пытается вести к общему экрану чужую модель вместо своей.
 *
 *  ⚠️ Расширять минимум можно, но каждое новое поле — это обязанность ОБОИХ
 *  клиентов. Поле, которого у веба нет в принципе (видео трека), приезжает
 *  отдельным необязательным пропом, а не полем трека. */

/** Строка текста песни. `t` необязателен: у plain-текста (без таймкодов)
 *  времени нет — и десктопный LyricLine (t: number), и веб-строка {text}
 *  подходят под эту форму. Сами экраны `t` не читают, он нужен только
 *  компоненту Lyrics дизайн-системы. */
export interface SharedLyricLine {
  t?: number;
  text: string;
  /** Объяснение смысла строки (Genius-аннотации): строка подчёркнута
   *  пунктиром, клик открывает карточку. У веба аннотаций пока нет. */
  note?: string;
}

/** Трек, как его видит экран «Сейчас играет».
 *
 *  ⚠️ НЕ СВОДИТЬ с QueueTrackData и LocalFileEntry из shell/contextTargets.ts
 *  (проверено чисткой дублей волны 3, 2026-08-02): те описывают, что меню
 *  ЧИТАЕТ для решения о пунктах, этот — что экран РИСУЕТ. Отсюда и разные
 *  поля: тут обложка/альбом/длительность, там `kind` и отпечаток файла. */
export interface NowPlayingTrack {
  id: string;
  title: string;
  artist: string;
  /** Пустая строка/отсутствие — альбом не показываем. */
  album?: string;
  /** null — обложки нет; плейсхолдер рисует Cover ДС, а не подставная
   *  картинка (фейковый арт на реальном треке — это ложь). */
  cover: string | null;
  /** Секунды. */
  duration: number;
}
