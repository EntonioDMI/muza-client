import type { Track } from "@muza/api-client";

/** Цель контекстного меню (ПКМ / кнопка «⋯») — только данные, без React.
 *
 *  Переехал из apps/desktop/src/shell/contextTargets.ts 2026-08-02: механизм
 *  меню общий для десктопа и веба, на старом месте — пенёк-ре-экспорт.
 *
 *  Разделение, на котором стоит механизм меню (2026-07-20):
 *  - ТРАНСПОРТ (стейт {open,x,y}, один <Menu> на приложение, клампинг в
 *    самом Menu) — shell/ContextMenu.tsx;
 *  - СОДЕРЖИМОЕ (какие пункты при какой роли) — чистая buildMenuItems в
 *    shell/menuActions.ts, тестируется матрицей без React.
 *
 *  Глобальные действия (радио, «В плейлист», шеринг…) живут в MenuContext и
 *  собираются один раз в App. Вьюшно-локальные (removeTrack плейлиста,
 *  forget локального файла, операции очереди) едут сюда замыканиями
 *  вызывателя в ctl — иначе их пришлось бы поднимать в App, где они не нужны.
 *
 *  ⚠️ Почему формы локального файла и трека очереди описаны ЗДЕСЬ, а не
 *  импортированы: их родные модули десктопа (lib/localFiles.ts — @tauri-apps,
 *  player/types.ts — движок воспроизведения) в общий пакет не поедут, а
 *  TypeScript структурный: десктопные LocalEntry и PlayerTrack подходят в эти
 *  поля без единой правки вызывателей. Поля перечислены НЕ все — только те,
 *  что меню действительно читает; лишние у вызывателя не мешают. */

/** Где показана строка трека: от места зависит набор пунктов
 *  («Заменить версию» — только Любимое; правка состава — только плейлист;
 *  для играющего сейчас (player) нет «Играть следующим» — он уже играет). */
export type TrackPlace = "search" | "home" | "favorites" | "stats" | "playlist" | "player";

/** Локальный файл устройства — структурная форма LocalEntry десктопа. */
export interface LocalFileEntry {
  hash: string;
  artist: string;
  title: string;
}

/** Трек очереди — структурная форма PlayerTrack десктопа. kind решает, есть ли
 *  пункт «В Любимое»: локальный файл без серверного id лайкать некуда. */
export interface QueueTrackData {
  id: string;
  kind: "catalog" | "local";
  title: string;
  artist: string;
}

export type ContextTarget =
  | {
      kind: "track";
      track: Track;
      place: TrackPlace;
      /** Вьюшно-локальные действия страницы плейлиста (place === "playlist").
       *  Поля-действия НЕОБЯЗАТЕЛЬНЫ: чего площадка не умеет — того в меню и
       *  нет (веб не переставляет треки внутри плейлиста, десктоп умеет всё). */
      ctl?: {
        changeIcon?: () => void;
        replaceVersion?: () => void;
        removeTrack?: () => void;
        moveToStart?: () => void;
        moveToEnd?: () => void;
        /** Владелец живого плейлиста: пункт «Сменить иконку плейлиста». */
        canChangeIcon: boolean;
        /** false у viewer/оффлайн — состав не правится. */
        canEdit: boolean;
      };
    }
  | { kind: "playlist"; id: string; name: string }
  | {
      kind: "queueTrack";
      track: QueueTrackData;
      ctl: {
        play: () => void;
        playNext: () => void;
        remove: () => void;
        clearAfter: () => void;
        /** false — это текущий или уже следующий трек. */
        canPlayNext: boolean;
        /** false — последний в очереди, чистить нечего. */
        canClearAfter: boolean;
      };
    }
  | {
      kind: "libraryBlank";
      /** Мультивыбор плиток (2026-07-20); нет — пункты выбора не показываются. */
      ctl?: {
        enterSelect: () => void;
        selectAll: () => void;
      };
    }
  | {
      kind: "playlistBlank";
      ctl: {
        /** Режим выбора: обычный клик начинает выделять. */
        enterSelect: () => void;
        selectAll: () => void;
      };
    }
  | {
      kind: "selection";
      /** Выделенные треки — id уже развёрнуты списком-хозяином в Track[].
       *  ВНИМАНИЕ: это КАТАЛОЖНАЯ форма, и локальные файлы в неё не
       *  превращаются — список короче реального выделения. Для действий это
       *  правильно (в плейлист или в «Любимое» локальный файл не положишь), а
       *  для счётчика — нет: см. count ниже. */
      tracks: Track[];
      /** Сколько выделено НА САМОМ ДЕЛЕ. Обязателен, потому что «Убрать из
       *  очереди» работает по полному набору id: в меню стояло «Выбрано: 2», а
       *  убиралось 3 (жалоба-разбор 2026-08-02). */
      count: number;
      /** queue — без «Играть следующим»/«В очередь»: они ДОБАВЛЯЮТ копии,
       *  а выделенное уже стоит в очереди. */
      place: "list" | "queue";
      ctl: {
        /** Убрать выделенное; scope выбирает подпись (плейлист/очередь). */
        remove?: { scope: "playlist" | "queue"; run: () => void };
        clear: () => void;
      };
    }
  | {
      kind: "playlistSelection";
      /** Выделенные плитки плейлистов медиатеки (свои и совместные —
       *  подписки вне выделения, как и вне реордера). */
      playlists: { id: string; name: string }[];
      ctl: {
        /** Нет поля — площадка не умеет держать плейлист на устройстве
         *  (браузер), и пункта «Сохранить офлайн» в меню нет вовсе. */
        saveOffline?: () => void;
        /** Открыть подтверждение массового удаления (диалог у вью). */
        requestDelete: () => void;
        clear: () => void;
      };
    }
  | {
      kind: "localTrack";
      entry: LocalFileEntry;
      ctl: {
        /** null — файл не зарегистрирован на сервере, класть в плейлист некуда. */
        addToPlaylist: (() => void) | null;
        /** null — файла нет на этом устройстве ИЛИ площадка не умеет открывать
         *  папку (браузер): пункта «Показать в папке» просто нет, не серый. */
        reveal: (() => void) | null;
        forget: () => void;
      };
    }
  | {
      kind: "lyrics";
      /** Весь текст песни (строки через \n) — главное действие ПКМ (2026-07-21). */
      allText: string;
      /** Строка под курсором; null — ПКМ мимо строк (между ними / по краям)
       *  или инструментальная пустая строка («•••» — копировать нечего). */
      lineText: string | null;
      lineIndex: number | null;
      /** У строки есть Genius-объяснение — дублируем «Смысл строки» пунктом
       *  (основной вход — двойной клик — не отменяется). */
      hasNote: boolean;
      ctl: {
        /** Открыть модалку смысла (та же, что по двойному клику). */
        explain: (i: number) => void;
      };
    };
