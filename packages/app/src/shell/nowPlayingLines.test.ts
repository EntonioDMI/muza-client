/** Лестница «высота окошка текста → сколько строк» в «Сейчас играет».
 *
 *  Заявка владельца 04.08 дословно: «сделать „Сейчас играет“ квадратом с
 *  адаптивным числом строк текста: маленький — текст скрыт, больше — одна
 *  строка, ещё больше — три или пять». Панель тянут за край (Ctrl+E) и
 *  сворачивают вместе с окном, поэтому фиксированное число строк в ней всегда
 *  либо не влезает, либо оставляет пустоту.
 *
 *  Живьём это не проверить дешёво: нужен играющий трек с синхронным текстом.
 *  Зато сама лестница — чистая функция, и её обещание держится здесь. */

import { describe, expect, it } from "vitest";
import { HIDE_LYRICS, lyricLinesForHeight } from "./NowPlayingPanel";

describe("сколько строк текста показывать по высоте окошка", () => {
  it("щель ниже строки — текста нет вовсе", () => {
    expect(lyricLinesForHeight(0)).toBe(HIDE_LYRICS);
    expect(lyricLinesForHeight(39)).toBe(HIDE_LYRICS);
  });

  it("чем выше окошко, тем больше строк — и ни разу наоборот", () => {
    const heights = [40, 96, 170, 260, 600];
    const lines = heights.map(lyricLinesForHeight);
    expect(lines).toEqual([1, 3, 5, 0, 0]);
    // 0 на верхних ступенях — «не подгонять кегль вовсе», обычный список во всю
    // высоту. Это НЕ «ноль строк»: ступень «строк нет» — отдельная, HIDE_LYRICS.
    expect(lines.filter((n) => n > 0)).toEqual([1, 3, 5]);
  });

  it("ступени идут подряд, без дыр между порогами", () => {
    // Ни одна высота от 0 до 400 не должна проваливаться мимо лестницы.
    for (let h = 0; h <= 400; h++) {
      const n = lyricLinesForHeight(h);
      expect([HIDE_LYRICS, 0, 1, 3, 5]).toContain(n);
    }
  });

  it("лестница монотонна: выше окошко — никогда не меньше строк", () => {
    // Сравниваем только подогнанные ступени (0 — верхняя, «без подгонки»).
    let prev = 0;
    for (let h = 40; h < 260; h++) {
      const n = lyricLinesForHeight(h);
      expect(n).toBeGreaterThanOrEqual(prev);
      prev = n;
    }
  });
});
