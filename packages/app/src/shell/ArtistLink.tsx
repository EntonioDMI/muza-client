/** Имя артиста, по которому можно перейти на его страницу.
 *
 *  ЗАЧЕМ ОТДЕЛЬНЫМ КОМПОНЕНТОМ (16.08, жалоба владельца «нажимаю на автора у
 *  трека, но не могу на него зайти»). Имя артиста показано в доброй дюжине
 *  мест, и во всех оно было мёртвым текстом. Сделать его кликабельным «на
 *  месте» значит развести по этим местам одинаковую разметку кнопки, сброс её
 *  стилей и остановку всплытия — а разъезжаться она начнёт с первой правки.
 *
 *  ⚠️ ВСПЛЫТИЕ ГАСИМ ОБЯЗАТЕЛЬНО. Имя почти всегда лежит ВНУТРИ строки или
 *  плитки, у которых свой клик — «играть». Без stopPropagation переход на
 *  артиста запускал бы заодно и песню, то есть жест делал бы две вещи разом.
 *
 *  ⚠️ Нет обработчика — нет и кнопки, остаётся обычный текст. Это то же
 *  правило площадок, что у пунктов меню: у веба страницы артиста пока нет
 *  вовсе, и подчёркнутое имя, никуда не ведущее, было бы обманом. */

import type { CSSProperties } from "react";

export function ArtistLink({
  name,
  onOpen,
  style,
}: {
  name: string;
  onOpen?: (name: string) => void;
  style?: CSSProperties;
}) {
  if (!onOpen || !name) return <span style={style}>{name}</span>;
  return (
    <button
      type="button"
      className="muza-artist-link"
      onClick={(e) => {
        e.stopPropagation();
        onOpen(name);
      }}
      // Строка трека слушает и двойной клик (играть) — без гашения он
      // сработал бы поверх уже случившегося перехода.
      onDoubleClick={(e) => e.stopPropagation()}
      style={{
        // Кнопка обязана выглядеть ровно как текст, среди которого стоит:
        // это по-прежнему подпись, а не элемент управления.
        background: "none",
        border: "none",
        padding: 0,
        margin: 0,
        font: "inherit",
        color: "inherit",
        textAlign: "inherit",
        cursor: "pointer",
        ...style,
      }}
    >
      {name}
    </button>
  );
}
