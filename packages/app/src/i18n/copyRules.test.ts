/** Сторож языка разработчика в пользовательских словарях (задание владельца
 *  19.07: «не разговаривать на языке разработчика и на языке маркетолога»).
 *
 *  Правило тона (спека 2026-07-19-настройки-ясность-и-кастомизация-дизайн):
 *  название = что это; подсказка = что произойдёт, если тронуть. Здесь
 *  проверяется механическая часть — запрещённые лексемы. Смысловая часть
 *  («это предложение?», «отвечает на „что изменится“?») — на ревью текста.
 *
 *  В бан-листе только ОДНОЗНАЧНЫЙ жаргон. Контекстные слова (сервер, лог,
 *  стрим, хост) сюда не входят — их вычищает волна 2 руками: механическая
 *  проверка по ним дала бы ложные срабатывания («каталог» содержит «лог»).
 *
 *  KNOWN_DEBT — снапшот нарушений, существовавших ДО волны 2 переписывания.
 *  Тест не даёт появляться НОВЫМ нарушениям и требует вычёркивать
 *  исправленные (запись в долге, которая больше не нарушает, — ошибка).
 *  Когда волна 2 закончится, массив станет пустым — удалить его совсем. */
import { describe, expect, it } from "vitest";
import { ru } from "./ru";
import { en } from "./en";

/** Однозначный жаргон. Лукбехайнды вместо \b: JS-\b не понимает кириллицу. */
const BANNED: { name: string; re: RegExp }[] = [
  // Чередование корня: добыЧа / добыВается / добыТых — одной формой не поймать
  { name: "добыча", re: /добыч|добыва|добыт/i },
  { name: "фолбэк", re: /фолб[эе]к|fallback/i },
  { name: "yt-dlp", re: /yt-dlp/i },
  { name: "токен", re: /(?<![а-яёa-z])токен|(?<![a-z])tokens?(?![a-z])/i },
  { name: "кэш", re: /(?<![а-яёa-z])к[эе]ш|(?<![a-z])cache/i },
  { name: "эндпоинт", re: /эндпо[ий]нт|endpoint/i },
  { name: "инстанс", re: /инстанс/i },
  { name: "namespace", re: /namespace/i },
  { name: "манифест", re: /манифест|manifest/i },
  { name: "дефолт", re: /дефолт/i },
  { name: "бэкенд/фронтенд", re: /б[эе]кенд|фронтенд|backend|frontend/i },
  { name: "DRM", re: /(?<![a-z])DRM(?![a-z])/ },
  { name: "битрейт/кодек", re: /битрейт|кодек|bitrate|codec/i },
  // Волна 2026-08-03. Каждое слово перед добавлением проверено грепом по обоим
  // словарям: ложных срабатываний нет ни одного (имена ключей вроде
  // streamQuality сторож не смотрит — он ходит только по значениям).
  { name: "RPC", re: /(?<![a-z])RPC(?![a-z])/i },
  { name: "стрим", re: /стрим|streaming/i },
  { name: "URL", re: /(?<![а-яёa-z])URLs?(?![a-z])/i },
];

/** Точечные разрешения: путь-префикс ключа, где термин — название, а не жаргон.
 *  - customize.css: «CSS» — имя функции для тех, кто умеет (спека §3);
 *  - system.licenses: лицензии обязаны называть библиотеки по имени (yt-dlp);
 *  - integrations.listenbrainz: «user token» — термин самого ListenBrainz,
 *    пользователь копирует его со страницы сервиса — переименование запутает;
 *  - views.admin: админ-панель видит только владелец — это инструмент
 *    разработчика, правило тона на него не распространяется. */
const ALLOWED_PREFIXES = ["settings.customize.css.", "settings.system.licenses.", "settings.integrations.listenbrainz.", "views.admin."];

function walk(node: unknown, path: string, out: { path: string; hit: string }[]) {
  if (typeof node === "string") {
    if (ALLOWED_PREFIXES.some((p) => path.startsWith(p))) return;
    for (const b of BANNED) {
      if (b.re.test(node)) out.push({ path, hit: b.name });
    }
    return;
  }
  if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node)) walk(v, path ? `${path}.${k}` : k, out);
  }
}

function violations(dict: object, lang: string): string[] {
  const out: { path: string; hit: string }[] = [];
  walk(dict, "", out);
  return out.map((v) => `${lang}:${v.path} [${v.hit}]`).sort();
}

// Снапшот-долг KNOWN_DEBT сожжён полностью 19.07 (волны 2 и 4) и удалён.
// С этого момента словари ЧИСТЫ: любое нарушение — новое, чинится сразу.
describe("словари не говорят языком разработчика", () => {
  it("жаргона нет ни в одном пользовательском тексте", () => {
    const found = [...violations(ru, "ru"), ...violations(en, "en")];
    expect(found, "жаргон в словаре — перепиши по правилу тона (спека 19.07 §2-3)").toEqual([]);
  });
});

/** Обращение на «вы» в русском словаре (решение 2026-08-03).
 *
 *  До этого дня словарь мешал два тона: 38 строк на «вы» и 32 на «ты», причём
 *  в соседних зонах — «Выберите готовый цвет» рядом с «Твоя медиатека», а
 *  внутри ОДНОГО экрана настроек «в твой профиль Last.fm» рядом с «увидят, что
 *  вы слушаете». Выбрано «ты»: это тон большинства экранов и лендинга.
 *
 *  Ловим две формы:
 *  1) местоимения вы/вас/вам/вами/ваш…;
 *  2) повелительное наклонение на -ите/-йте/-ьте («Выберите», «Нажмите»,
 *     «Проверьте»).
 *
 *  ⚠️ Пункт 2 — эвристика, и у неё есть законный класс ложных срабатываний:
 *  существительные в косвенном падеже на -ите («о защите», «на орбите»). Такое
 *  сработает — не глуши правило целиком: перефразируй строку либо добавь путь
 *  ключа в TONE_ALLOWED ниже, объяснив, почему это не обращение.
 *
 *  Английский словарь не проверяется: в нём этой развилки нет. */
const YOU_FORMS: { name: string; re: RegExp }[] = [
  { name: "вы/вас/вам/ваш", re: /(?<![а-яё])(вы|вас|вам|вами|ваш[а-яё]*)(?![а-яё])/i },
  { name: "повелительное на -ите/-йте/-ьте", re: /(?<![а-яё])[а-яё]{2,}(ите|йте|ьте)(?![а-яё])/i },
];

/** Пути, где «вы»-форма — не обращение (пока пусто; см. предупреждение выше). */
const TONE_ALLOWED: string[] = [];

function toneWalk(node: unknown, path: string, out: string[]) {
  if (typeof node === "string") {
    if (TONE_ALLOWED.some((p) => path.startsWith(p))) return;
    for (const f of YOU_FORMS) {
      const m = f.re.exec(node);
      if (m) out.push(`ru:${path} [${m[0]}]`);
    }
    return;
  }
  if (node && typeof node === "object") {
    for (const [k, v] of Object.entries(node)) toneWalk(v, path ? `${path}.${k}` : k, out);
  }
}

describe("русский словарь обращается на «ты»", () => {
  it("ни одной строки на «вы»", () => {
    const found: string[] = [];
    toneWalk(ru, "", found);
    expect(found.sort(), "смешение «ты» и «вы» — приведи строку к «ты» (решение 2026-08-03)").toEqual([]);
  });
});
