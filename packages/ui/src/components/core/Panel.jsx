import React from "react";

/** Панель раздела: заголовок, необязательное действие справа и содержимое на
 *  карточной плёнке.
 *
 *  ПОЧЕМУ ЭТО ПРИМИТИВ. «Раздел страницы» рисовали инлайном как минимум два
 *  экрана — Статистика (Panel внутри StatsView) и Админка (Section) — и они
 *  успели разъехаться: у одного карточка без места под действие, у другого
 *  голый заголовок без карточки вовсе. Одна и та же сущность выглядела
 *  по-разному на соседних экранах, а правилась в двух файлах.
 *
 *  МАТЕРИАЛ — surface-2, а не surface-1: плёнка 2.5 % белого поверх стекла
 *  зоны отличается от фона меньше чем на ступень тона, и карточки на странице
 *  просто не видно (разбор — шапка Panel в StatsView.tsx). Контраст текста на
 *  surface-2 гарантирован сторожем стеклянной лестницы (themeVars.test.ts).
 *
 *  action — правый край ШАПКИ, а не полоса над содержимым: так содержимое всех
 *  панелей страницы начинается с одной высоты, и глазу не приходится заново
 *  искать начало данных в каждой карточке.
 *
 *  flush — содержимое идёт во всю ширину карточки. Это для списков, у строк
 *  которых есть свой внутренний отступ и своя подсветка (TrackRow, Table): без
 *  flush строка получает двойное поле, а её ховер не доезжает до края и
 *  читается как обрезанный.
 *
 *  flex/minWidth в корне — чтобы панель работала элементом flex-ленты (так
 *  Статистика раскладывает блоки). Вне flex-контейнера оба свойства ничего не
 *  делают, поэтому стоят безусловно, без пропа-переключателя. */
export function Panel({ title, action, flush = false, children, style }) {
  const head = title != null || action != null;
  return (
    <section
      style={{
        flex: 1,
        minWidth: 0,
        background: "var(--surface-2)",
        borderRadius: "var(--r-md)",
        padding: flush ? "var(--sp-5) var(--sp-3) var(--sp-3)" : "var(--sp-5)",
        ...style,
      }}
    >
      {head ? (
        <div
          style={{
            display: "flex",
            alignItems: "center",
            gap: "var(--sp-3)",
            /* при flush заголовок отбит внутрь на поле строки списка — иначе
               он висит левее данных и колонка текста ломается на глаз */
            margin: flush ? "0 var(--sp-2) var(--sp-4)" : "0 0 var(--sp-4)",
          }}
        >
          <h2
            style={{
              flex: 1,
              minWidth: 0,
              margin: 0,
              fontSize: "var(--fs-title)",
              fontWeight: "var(--fw-bold)",
              letterSpacing: "var(--ls-title)",
              color: "var(--text-1)",
            }}
          >
            {title}
          </h2>
          {action != null ? (
            <div style={{ flex: "none", display: "flex", alignItems: "center", gap: "var(--sp-2)" }}>{action}</div>
          ) : null}
        </div>
      ) : null}
      {children}
    </section>
  );
}
