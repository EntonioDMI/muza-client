/** ФОНОВОЕ СВЕЧЕНИЕ ПО ОБЛОЖКЕ.
 *
 *  Приём из наборов вроде KokonutUI / Magic UI (там это «aurora»), но взятый
 *  так, как он уместен музыке: панель окрашивается тем, что сейчас играет.
 *  Смена трека — смена настроения панели; это единственная анимация здесь,
 *  и человек видит её ровно столько раз, сколько включает песни.
 *
 *  ⚠️ ЭТО CSS, А НЕ WEBGL И НЕ ЧАСТИЦЫ. В наборах такой фон обычно рисуется
 *  шейдером на canvas: красиво в витрине, но это постоянный кадр-за-кадром
 *  расход на экране, который у человека открыт весь день. Здесь — размытая
 *  копия ТОЙ ЖЕ картинки, которая и так загружена для обложки: ни одного
 *  лишнего запроса, ни одного кадра анимации в покое.
 *
 *  ⚠️ ЦВЕТ НЕ ВЫЧИСЛЯЕТСЯ. Соблазн «достать доминирующий цвет» требует
 *  canvas, чтения пикселей и обхода CORS у чужих обложек. Размытие даёт тот
 *  же результат честнее: это и есть усреднение цвета, только его делает
 *  видеокарта.
 *
 *  Ничего не показывает без картинки — плейсхолдер обложки цвета не имеет, и
 *  светиться нечему.
 */
export function CoverGlow({ src, className, style }) {
  if (!src) return null;
  return (
    // ⚠️ КАРТИНКОЙ, А НЕ background-image: адрес обложки приходит от чужой
    // площадки, и подставлять его в строку CSS `url(...)` — это подстановка
    // чужого текста в правило. У <img> такой поверхности нет вовсе.
    <img
      src={src}
      alt=""
      aria-hidden="true"
      draggable={false}
      className={className}
      style={{
        position: "absolute",
        // Вылезает за края и обрезается родителем: у размытия края всегда
        // бледнее середины, и без выхода за границу была бы видна рамка.
        inset: "-15%",
        width: "130%",
        height: "130%",
        objectFit: "cover",
        filter: "blur(56px) saturate(1.6)",
        opacity: 0.5,
        // Не ловит мышь: это фон, а не поверхность.
        pointerEvents: "none",
        // ⚠️ ОТРИЦАТЕЛЬНЫЙ z-index РАБОТАЕТ ТОЛЬКО ВНУТРИ СВОЕГО КОНТЕКСТА
        // НАЛОЖЕНИЯ. Родитель ОБЯЗАН его создать (`isolation: isolate`), иначе
        // выбор такой: 0 — и слой рисуется ПОВЕРХ обычного содержимого, накрывая
        // панель, либо -1 — и он уезжает под фон предка, где его не видно вовсе.
        // С контекстом же -1 ложится ровно куда нужно: над фоном панели, под её
        // содержимым.
        zIndex: -1,
        ...style,
      }}
    />
  );
}
