/** Страховка на случай, если transitionend не придёт: узел мог быть скрыт
 *  display:none, вкладка — уснуть, свойство — не измениться вовсе. Считаем от
 *  ЖИВОЙ длительности узла, а не от зашитой константы: ползунок скорости
 *  анимаций растягивает уход, и фикс-таймер снимал бы слой на середине.
 *
 *  Возвращает 0, когда длительности не видно (jsdom, узла нет) — вызывающий
 *  сам решает, что делать: обычно снять слой немедленно.
 *  @param {Element | null | undefined} node
 *  @returns {number} миллисекунды
 */
export function readDurationMs(node) {
  if (!node || typeof getComputedStyle !== "function") return 0;
  const cs = getComputedStyle(node);
  // Берём максимум по обоим спискам: у слоя может быть и transition, и
  // остаточная animation, а снимать его можно только когда стихло всё.
  const longest = (list) =>
    String(list || "")
      .split(",")
      .reduce((max, part) => {
        const raw = part.trim();
        if (!raw) return max;
        const ms = raw.endsWith("ms") ? parseFloat(raw) : raw.endsWith("s") ? parseFloat(raw) * 1000 : NaN;
        return Number.isFinite(ms) ? Math.max(max, ms) : max;
      }, 0);
  return Math.max(longest(cs.transitionDuration), longest(cs.animationDuration));
}
