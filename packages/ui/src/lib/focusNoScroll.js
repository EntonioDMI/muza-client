/** Ставить фокус ВНУТРИ плавающего слоя (меню, диалог, выпадающий список,
 *  выбор цвета) можно только так — иначе браузер подкручивает страницу.
 *
 *  ⚠️ ЖИВАЯ ЖАЛОБА ВЛАДЕЛЬЦА 03.08: «когда я открываю устройство вывода, у
 *  меня весь экран улетает вверх». Причина — не вёрстка меню, а обычный
 *  `element.focus()`: по умолчанию он прокручивает ближайшего прокручиваемого
 *  предка так, чтобы элемент оказался видимым. Панель у нас `position: fixed`
 *  и уже стоит там, где нужно, — а прокручивается при этом ВСЁ приложение под
 *  ней, и человек видит, как экран уезжает.
 *
 *  Коварство в том, что баг появился ВМЕСТЕ с починкой: до 03.08 фокус в меню
 *  не входил вовсе (гонка монтирования), поэтому и прокрутки не было. Починили
 *  клавиатуру — получили уезжающий экран. Поэтому правило записано отдельным
 *  файлом, а не спрятано в один компонент: любой новый плавающий слой обязан
 *  использовать его же.
 *
 *  Где НЕ применять: возврат фокуса на кнопку, которая открыла слой. Она живёт
 *  в обычном потоке страницы, и там прокрутка к ней — правильное поведение,
 *  если человек успел увести список. */
export const NO_SCROLL = { preventScroll: true };
