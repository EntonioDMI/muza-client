/** КУДА ПОРТАЛИТЬ ПЛАВАЮЩИЕ СЛОИ (меню, диалоги, выпадашки, палитра).
 *
 *  ЗАЧЕМ ВООБЩЕ ПОРТАЛ. Все эти слои — position: fixed. По спецификации любой
 *  предок с filter, backdrop-filter, transform, perspective, will-change или
 *  contain: paint создаёт для fixed-потомков НОВЫЙ содержащий блок: отсчёт идёт
 *  от предка, а не от окна. А стекло — это и есть backdrop-filter. Поэтому
 *  меню, отрисованное внутри стеклянной панели, уезжает ровно на её смещение.
 *
 *  Живой замер (владелец, 03.08): меню «Устройство вывода» рисуется прямо
 *  внутри полосы плеера, у которой backdrop-filter стоял всегда. CSS говорил
 *  top: 633px, на экране меню оказывалось на 1429 — на 796px ниже, целиком за
 *  краем окна. 796 — это в точности отступ полосы плеера сверху. Кнопка «не
 *  открывала ничего»: слой открывался, просто вне экрана.
 *  Волна «больше стекла» (03.08) расширила беду: backdrop-filter появился ещё у
 *  сайдбара, «Сейчас играет» и рельса настроек — сломались бы и выпадашки
 *  настроек, и меню плейлиста, и палитра в «Кастомизации».
 *
 *  ⚠️ ЦЕЛЬ — НЕ document.body. Тема Muza живёт ИНЛАЙНОМ на своём div (App.tsx
 *  rootStyle: все --glass-*, --accent-*, --text-*, data-theme и, главное, zoom
 *  масштаба интерфейса). Портал в body выкинул бы слой из этого div, и меню
 *  красилось бы дефолтами дизайн-системы вместо темы пользователя, а на
 *  масштабе != 100 % ещё и промахивалось координатами — ровно та беда, из-за
 *  которой DragLayer держат внутри theme-div (см. комментарий в App.tsx).
 *  Поэтому целью объявлен САМ theme-div: у него есть все переменные и нет ни
 *  одного свойства, создающего содержащий блок (overflow: hidden сам по себе
 *  fixed-потомков не обрезает — обрезает только содержащий блок).
 *
 *  Кто цель — говорит разметка приложения атрибутом data-muza-layer-root.
 *  Нет его (тесты, чужой потребитель @muza/ui, первая отрисовка) — падаем в
 *  document.body: там слой хотя бы не уедет, просто возьмёт дефолтные токены. */

import { createPortal } from "react-dom";

/** Узел, в который порталить слой. null — рендерить на месте (нет DOM: SSR). */
export function getLayerRoot() {
  if (typeof document === "undefined") return null;
  return document.querySelector("[data-muza-layer-root]") ?? document.body;
}

/** Обёртка для плавающего слоя: портал, если есть куда, иначе рендер на месте.
 *  Считает цель НА КАЖДОМ РЕНДЕРЕ, а не один раз при загрузке модуля: theme-div
 *  появляется позже модуля, а в тестах перерождается на каждый рендер. */
export function portal(node) {
  const root = getLayerRoot();
  return root ? createPortal(node, root) : node;
}
