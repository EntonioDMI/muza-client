/** ПОЗИЦИЯ ВОСПРОИЗВЕДЕНИЯ ЖИВЁТ ЗДЕСЬ, А НЕ В СОСТОЯНИИ REACT.
 *
 *  ЗАЧЕМ. <audio> шлёт timeupdate ~4 раза в секунду. Пока позиция была
 *  useState внутри usePlayback, каждый такой тик перерисовывал ВЕСЬ App
 *  (2700 строк): сайдбар, текущий экран со всеми строками треков, очередь,
 *  панель «Сейчас играет» с текстом песни, полосу плеера и оверлей караоке со
 *  ВТОРОЙ копией того же текста. React.memo в проекте не используется нигде, и
 *  «просто навесить memo» не помогло бы: пропы уезжают вниз новыми стрелками и
 *  объектными литералами, память сравнения промахивалась бы всегда. Здесь
 *  лечится причина — значение переехало из состояния в отдельное хранилище, и
 *  на тик перерисовываются ровно те узлы, которые на него подписались.
 *
 *  ⚠️ ЧЕГО НЕЛЬЗЯ ДЕЛАТЬ — «упростить» это до «обновлять позицию пореже».
 *  ТОЧНАЯ позиция обязана считаться ВСЕГДА и на КАЖДЫЙ тик; тормозится только
 *  ПЕРЕРИСОВКА. Наивная версия («окно свёрнуто — двигаем позицию раз в
 *  секунду») ломает ровно три вещи, и все три человек слышит или видит:
 *
 *   1. «Слушаем вместе». Хост шлёт гостю свою позицию, гость сверяет её со
 *      своей (player/useJam.ts). Порог дрейфа — 3 секунды; загрубление на
 *      секунду с обеих сторон добивает реальное расхождение до порога, и у
 *      гостя срабатывает seek: музыка в наушниках прыгает на ходу.
 *   2. Мини-плеер поверх игры. В снапшот отдельного окна уходит СЫРАЯ позиция
 *      (App.tsx, miniStateNow) — его часы отстали бы на секунду и застряли бы
 *      такими на всю паузу.
 *   3. Discord Rich Presence. startTs считается от позиции (App.tsx) — чужие
 *      люди видели бы неверное время.
 *
 *  Поэтому get() отдаёт точное значение всегда, а «пореже» бывает только у
 *  ПОДПИСОК: subscribeSecond будит потребителя на смене целой секунды (там,
 *  где потребитель и так целосекундный — системный медиа-оверлей, мини-плеер,
 *  событие «position» плагинам), subscribe — на каждый тик (полоса плеера,
 *  текст песни: они рисуют плавно).
 *
 *  Хранилище СВОЁ У КАЖДОГО usePlayback (не модульный синглтон): плееров в
 *  окне один, но модульное состояние протекает между тестами и между
 *  перемонтированиями. */

import { useSyncExternalStore, type ReactNode } from "react";

export interface PositionStore {
  /** Точная позиция в секундах ПРЯМО СЕЙЧАС. Рендер не вызывает, стоит ноль. */
  get(): number;
  /** Целые секунды — снимок для потребителей, которые и так их округляют. */
  getSecond(): number;
  /** Новый тик. Будит подписчиков; на целых секундах — ещё и «секундных». */
  set(sec: number): void;
  /** Каждый тик (~4 Гц). */
  subscribe(onChange: () => void): () => void;
  /** Только смена ЦЕЛОЙ секунды (~1 Гц). */
  subscribeSecond(onChange: () => void): () => void;
}

export function createPositionStore(initial = 0): PositionStore {
  let sec = initial;
  const onTick = new Set<() => void>();
  const onSecond = new Set<() => void>();
  return {
    get: () => sec,
    getSecond: () => Math.floor(sec),
    set(next: number) {
      if (next === sec) return; // тот же timeupdate дважды (пауза) — будить некого
      const wasWhole = Math.floor(sec);
      sec = next;
      // копия набора: отписка из обработчика не должна ломать обход
      for (const fn of [...onTick]) fn();
      if (Math.floor(next) !== wasWhole) for (const fn of [...onSecond]) fn();
    },
    subscribe(onChange) {
      onTick.add(onChange);
      return () => {
        onTick.delete(onChange);
      };
    },
    subscribeSecond(onChange) {
      onSecond.add(onChange);
      return () => {
        onSecond.delete(onChange);
      };
    },
  };
}

/** Подписка-пустышка для live={false}: значение читается на рендере родителя
 *  и остаётся замороженным до следующего его рендера. */
const NEVER = () => () => {};

/** Позиция с подпиской. live=false — «читаем, но не подписываемся»: узел
 *  перерисуется только вместе с родителем, зато значение возьмёт свежее. */
export function usePosition(store: PositionStore, live = true): number {
  return useSyncExternalStore(live ? store.subscribe : NEVER, store.get, store.get);
}

/**
 * Единственный узел, который перерисовывается на тик позиции. Всё остальное
 * дерево остаётся нетронутым — в этом и смысл файла.
 *
 * `live={false}` — для потребителей, которых в этот момент НЕ ВИДНО, и это
 * доказано их собственным кодом (полоса и часы закрытого караоке под
 * visibility:hidden; часы видео панели «Сейчас играет», которую караоке
 * накрывает непрозрачным оверлеем). Замораживается только ЗНАЧЕНИЕ ПРОПА:
 * когда состояние окна меняется, родитель перерисовывается и узел получает
 * точную позицию В ТОМ ЖЕ КОММИТЕ, что и «открыто» — первый же нарисованный
 * кадр появления правильный, догоняющего рывка нет.
 *
 * ⚠️ Номер активной строки текста через это НЕ гейтится (см.
 * DerivedPositionScope): текст обязан продолжать следить за песней даже
 * невидимым, иначе на открытии караоке он поедет плавной прокруткой через
 * весь куплет — это видно.
 */
export function PositionScope({
  store,
  live = true,
  children,
}: {
  store: PositionStore;
  live?: boolean;
  children: (pos: number) => ReactNode;
}): ReactNode {
  return children(usePosition(store, live));
}

/**
 * То же, но для ЧИСЛА, посчитанного из позиции (номер активной строки текста).
 * Подписка идёт на каждый тик, а дети перерисовываются только когда само
 * число сменилось: строка меняется раз в несколько секунд, тик — четыре раза
 * в секунду. Считать обязано быть чистым и дешёвым — зовётся на каждый тик.
 */
export function DerivedPositionScope({
  store,
  compute,
  children,
}: {
  store: PositionStore;
  compute: (sec: number) => number;
  children: (value: number) => ReactNode;
}): ReactNode {
  const snapshot = () => compute(store.get());
  return children(useSyncExternalStore(store.subscribe, snapshot, snapshot));
}
