/** Якорь медиасессии: тихий зацикленный `<audio>`, который держит за нас
 *  системную медиасессию Windows (SMTC), пока звук идёт мимо WebView2.
 *
 *  ЗАЧЕМ ЭТО ВООБЩЕ ЕСТЬ (регрессия 10.08, найдена 14.08).
 *  `navigator.mediaSession` — не «объявление о себе», а НАДСТРОЙКА над реально
 *  играющим медиаэлементом. Хромиум отдаёт странице системную сессию (а вместе
 *  с ней медиаклавиши и оверлей Win+ с обложкой) только когда в этой вкладке
 *  играет `<audio>`/`<video>`: сессия рождается из «audio focus», а focus
 *  запрашивают ПЛЕЕРЫ, а не вызовы `setActionHandler`. Так это и написано в
 *  спецификации («guessed playback state» считается по медиаэлементам,
 *  w3c/mediasession) и в документации хромиума (services/media_session:
 *  «Each WebContents … will request Gain audio focus»).
 *
 *  Пока весь звук Музы шёл через `<audio>`, надстройка стояла на фундаменте и
 *  всё работало. 10.08 (коммит b762129) файлы из кэша уехали играть НАТИВНО —
 *  Rust + cpal, мимо WebView2. Медиаэлемент замолчал, фундамент исчез, и вместе
 *  с ним у Музы пропала системная сессия: метаданные и обработчики продолжали
 *  ставиться исправно и уходили в никуда. Симптом у владельца — «FN+F7/F8/F9 не
 *  делают ничего», а точнее делают: клавиша уходит ТОМУ, у кого сессия есть
 *  (у него это была вкладка с ютубом в Chrome).
 *
 *  ЗАМЕР, НА КОТОРОМ ЭТО ДОКАЗАНО (14.08, Edge = тот же движок, что WebView2;
 *  сессии читались из Windows через GlobalSystemMediaTransportControlsSessionManager):
 *    страница на http-origin, metadata + 5 обработчиков + playbackState="playing",
 *    медиаэлемента нет            → сессий приложения в системе: НЕТ
 *    та же страница + этот якорь  → сессия есть, с нашим title/artist,
 *                                   и она же CurrentSession, т.е. получатель клавиш
 *  Пауза якоря сессию НЕ убивает (status=Paused) — поэтому «play» с клавиатуры
 *  доезжает и из паузы.
 *
 *  ПОЧЕМУ ИМЕННО ТИШИНА, А НЕ ЧЕСТНЫЙ ЗВУК. Нам нужен только повод для системы
 *  считать, что вкладка играет; сам звук делает нативный движок (ради него всё
 *  и затевалось — «захват аудио приложения» не слышит WebView2, см. шапку
 *  nativeEngine.ts). Цена якоря — один поток 8 кГц моно с нулями в микшере
 *  Windows.
 *
 *  ГРАБЛИ, ПРОВЕРЕННЫЕ ЗАМЕРОМ, — НЕ ТРОГАТЬ БЕЗ ПОВТОРНОЙ ПРОВЕРКИ:
 *  • `muted = true` или `volume = 0` НЕ ГОДЯТСЯ: беззвучный по флагам элемент
 *    audio focus не получает. Тишина должна быть в САМИХ СЭМПЛАХ.
 *  • Источник — `blob:`, и это НЕ вкусовщина: в CSP приложения (tauri.conf.json,
 *    и dev-, и прод-профиль) у `media-src` разрешён `blob:`, а `data:` — нет
 *    (он там только у img-src и font-src). Якорь на `data:`-URL молча не
 *    загрузится: элемент навсегда останется в readyState 0, сессии не будет, и
 *    выглядеть это будет как «починка не сработала». Обратная сторона: `blob:`
 *    наследует origin страницы и на opaque-origin (проверено на `file://`)
 *    мёртв — приложению это не грозит, оно живёт на `http://tauri.localhost`.
 *    Менять источник — только вместе с CSP, а CSP вшивается в бинарь при сборке.
 *  • Длина — 5 с. Хромиум даёт короткому звуку не полный фокус, а «ducking»
 *    (документация: «media duration is at least 5 seconds», чтобы всякие
 *    «дзынь» не лезли в системный оверлей). Замер показал, что зацикленной
 *    секунды сегодня тоже хватает, но правило написано про длину — держим её.
 *  • Автозапуск: `play()` без жеста пользователя разрешён аргументом
 *    `--autoplay-policy=no-user-gesture-required` (tauri.conf.json). Отказ всё
 *    равно глотаем: без якоря плеер играет, просто без системных клавиш.
 *
 *  ПОЧЕМУ ЯКОРЬ НЕ ПОДНИМАЕТСЯ ПРОСТО ОТ ЗАПУСКА ПРИЛОЖЕНИЯ. Сессия — это ещё
 *  и право на медиаклавиши, отнятое у чужих плееров. Пока человек ничего не
 *  включил, отбирать клавишу у его Spotify мы не вправе: якорь рождается на
 *  первом `hold()`, то есть на первом реальном воспроизведении, и умирает
 *  вместе с треком (`release()`).
 *
 *  Кто им управляет — useMediaSession.ts (там же метаданные, позиция и кнопки).
 */

/** WAV с тишиной: 8 кГц, моно, 8 бит. В 8-битном PCM тишина — это 128, а не 0.
 *  Длина по умолчанию — 5 с, см. правило про «короче 5 секунд» в шапке.
 *
 *  Собираем байты руками, а не тащим файл в ассеты: пять секунд восьмибитной
 *  тишины — это 40 КБ, которые здесь укладываются в 30 строк и не заводят в
 *  сборке бинарный артефакт, который потом никто не опознает. */
export function silentWavBytes(seconds = 5): Uint8Array<ArrayBuffer> {
  const rate = 8000;
  const samples = Math.round(rate * seconds);
  const buf = new ArrayBuffer(44 + samples);
  const view = new DataView(buf);
  const ascii = (offset: number, text: string) => {
    for (let i = 0; i < text.length; i++) view.setUint8(offset + i, text.charCodeAt(i));
  };
  ascii(0, "RIFF");
  view.setUint32(4, 36 + samples, true);
  ascii(8, "WAVEfmt ");
  view.setUint32(16, 16, true); // размер fmt-куска
  view.setUint16(20, 1, true); // PCM
  view.setUint16(22, 1, true); // моно
  view.setUint32(24, rate, true);
  view.setUint32(28, rate, true); // байт в секунду = rate × 1 канал × 1 байт
  view.setUint16(32, 1, true); // выравнивание блока
  view.setUint16(34, 8, true); // бит на сэмпл
  ascii(36, "data");
  view.setUint32(40, samples, true);
  const bytes = new Uint8Array(buf);
  bytes.fill(128, 44);
  return bytes;
}

/** Тот же WAV, но ссылкой для `<audio>`. Отдельной функцией — чтобы байты выше
 *  можно было проверить тестом, не подсовывая jsdom создание blob-ссылок. */
export function silentWavUrl(seconds = 5): string {
  return URL.createObjectURL(new Blob([silentWavBytes(seconds)], { type: "audio/wav" }));
}

export interface MediaAnchor {
  /** Трек играет — держим сессию (элемент создаётся при первом вызове). */
  hold(): void;
  /** Трек на паузе — якорь тоже на паузе. Сессия остаётся: система показывает
   *  «Муза, на паузе» и отдаёт нам клавишу «play». Если якоря ещё нет — не
   *  создаём: пауза без единого воспроизведения сессии не заслуживает. */
  suspend(): void;
  /** Трека нет или медиаклавиши выключены в настройках — отпускаем сессию.
   *  `src = ""` — рекомендованный способ убрать системную карточку. */
  release(): void;
  /** Живой элемент (или null). Для тестов и отладки. */
  readonly element: HTMLAudioElement | null;
}

export function createMediaAnchor(): MediaAnchor {
  let el: HTMLAudioElement | null = null;
  // Ссылку заводим один раз и НЕ отзываем в release(): это 40 КБ тишины на всё
  // время работы приложения против пересборки блоба на каждый трек. Отзыв
  // (revokeObjectURL) пришлось бы делать ровно тогда, когда элемент ещё может
  // на неё сослаться, — цена ошибки выше цены сорока килобайт.
  let url: string | null = null;

  return {
    get element() {
      return el;
    },
    hold() {
      if (!el) {
        url ??= silentWavUrl();
        el = new Audio(url);
        el.loop = true;
        // Явно, хотя это и значения по умолчанию: см. грабли в шапке — беззвучный
        // по флагам элемент системной сессии не получает, и «оптимизация» вида
        // «зачем нам громкость у тишины» ломает всё молча.
        el.volume = 1;
        el.muted = false;
      }
      if (!el.paused) return; // уже держим — не дёргаем play() на каждый рендер
      // `?.` не лишний: промис у play() появился не всегда и не везде (в jsdom
      // его нет вовсе), а падение здесь уронило бы весь плеер ради якоря.
      void el.play()?.catch(() => {
        /* автозапуск не дали — плеер играет, просто без системных клавиш */
      });
    },
    suspend() {
      if (el && !el.paused) el.pause();
    },
    release() {
      if (!el) return;
      el.pause();
      el.src = "";
      el = null;
    },
  };
}

/** Общий якорь приложения: медиасессия в документе одна, значит и якорь один. */
export const mediaAnchor = createMediaAnchor();
