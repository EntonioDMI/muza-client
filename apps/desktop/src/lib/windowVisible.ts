/** ВИДНО ЛИ ОКНО — сигнал от СИСТЕМЫ, а не от страницы.
 *
 *  ⚠️ ПОЧЕМУ ЗДЕСЬ НЕ `document.hidden` И НЕ `visibilitychange`. Потому что в
 *  WebView2 страница вообще не узнаёт, что окно свёрнуто. Замер 03.08 (чистый:
 *  отладчик отключён — он сам снимает торможение фоновых вкладок и делал
 *  первое измерение недействительным): окно свёрнуто на 20 секунд, кадров
 *  3425 — то есть 171 кадр/с; `document.visibilityState` всё это время
 *  `"visible"`, событий `visibilitychange` — НИ ОДНОГО. Без окна цикл кадров
 *  перестаёт ждать развёртку экрана и разгоняется выше 60 Гц, поэтому расход
 *  при играющей музыке у свёрнутого окна ВЫШЕ, чем у открытого: 177% одного
 *  ядра против 170%. Свернуть Музу было дороже, чем оставить её на виду —
 *  ровно та жалоба владельца, что «в играх падает ФПС».
 *
 *  Следствие, которое обязан знать каждый, кто это читает: любой гейт вида
 *  `if (document.hidden)` в ЭТОМ приложении мёртв — он не срабатывает никогда,
 *  и «упростить» файл до него нельзя. Флаг запуска
 *  `--enable-features=CalculateNativeWinOcclusion` тоже пробован и не помог
 *  (кадры остались 180 к/с). Единственный работающий путь — спросить систему
 *  через Rust: `src-tauri/src/window_visibility.rs` раз в 800 мс опрашивает
 *  Win32 и НА СМЕНУ СОСТОЯНИЯ шлёт сюда событие. Таблица замеров и карта всех
 *  потребителей кадров — `docs/subsystems/производительность-интерфейса.md`.
 *
 *  ЧТО СЧИТАЕТСЯ «НЕ ВИДНО» (решение владельца 03.08): свёрнуто ИЛИ полностью
 *  накрыто одним другим окном. Состояние «видно, но не в фокусе» — это ВИДНО:
 *  окно на втором мониторе человек видит, и замершая анимация там заметна.
 *
 *  ОШИБАЕМСЯ В СТОРОНУ «РИСУЕМ». По умолчанию `true`, пока событие не пришло;
 *  если подписка не удалась (запуск вне Tauri, тесты, сбой IPC) — молча
 *  остаёмся в `true` навсегда. Лишние кадры — потеря производительности,
 *  ложное «не видно» — замершая картинка на глазах у пользователя. */

import { useSyncExternalStore } from "react";
import { listen, type UnlistenFn } from "@tauri-apps/api/event";

/** Имя события. Зеркало `EVENT` из src-tauri/src/window_visibility.rs. */
const EVENT = "muza://window-visible";

let visible = true;
/** Подписчики React. Подписка на нативное событие ОДНА на всё приложение —
 *  сколько бы хуков её ни спросили. */
const listeners = new Set<() => void>();
let unlisten: UnlistenFn | null = null;
/** Подписка Tauri едет через IPC, то есть асинхронно: между запросом и ответом
 *  успевает произойти и уход последнего потребителя, и приход нового. */
let pending: Promise<UnlistenFn> | null = null;

function apply(next: boolean): void {
  if (next === visible) return;
  visible = next;
  // копия набора: снятие подписки в обработчике не должно ломать обход
  for (const notify of [...listeners]) notify();
}

function attach(): void {
  if (unlisten || pending) return;
  let started: Promise<UnlistenFn>;
  try {
    // Гасим ТОЛЬКО по явному false. Нагрузка события — boolean, но если она
    // однажды приедет мусором (смена контракта, чужой emit), правильный исход
    // — рисовать, а не заморозить окно на глазах у человека.
    started = listen<boolean>(EVENT, (e) => apply(e.payload !== false));
  } catch {
    return; // вне Tauri listen может бросить сразу — остаёмся в true
  }
  pending = started;
  void started.then(
    (off) => {
      pending = null;
      if (listeners.size === 0) {
        off(); // пока ехала подписка, последний потребитель ушёл
        return;
      }
      unlisten = off;
    },
    () => {
      pending = null; // подписки нет (нет Tauri) — молча живём в true
    },
  );
}

function detach(): void {
  // Подписку, которая ещё едет, снимет её же обработчик выше: он видит пустой
  // набор потребителей. Здесь снимаем только уже установленную.
  const off = unlisten;
  unlisten = null;
  // Без подписки состояние знать неоткуда, а событие приходит лишь на СМЕНУ:
  // застрявший false заморозил бы анимации у видимого окна после повторного
  // монтирования. Возвращаемся в безопасное «видно».
  visible = true;
  if (off) off();
}

/** Подписка для useSyncExternalStore — стабильная ссылка, иначе React
 *  переподписывался бы на каждый рендер потребителя. */
function subscribe(notify: () => void): () => void {
  listeners.add(notify);
  attach();
  return () => {
    listeners.delete(notify);
    if (listeners.size === 0) detach();
  };
}

function snapshot(): boolean {
  return visible;
}

/** Видно ли окно приложения. `true`, пока система не сказала обратного. */
export function useWindowVisible(): boolean {
  // третий аргумент (сервер/пререндер) — тот же безопасный «видно»
  return useSyncExternalStore(subscribe, snapshot, () => true);
}
